-- Reworked Salary Payouts screen (src/modules/expenses/SalaryPayouts.jsx):
-- a simple ad-hoc payment log, deliberately separate from the existing
-- accrual/adjustment ledger (ledger_entries ledger_type='user_salary',
-- pay_employee RPC) — that system is being revisited later; this is not
-- an attempt to replace or reconcile it yet.
--
-- Two tables: a payout_batches header (one row per "Save Payout" click,
-- carrying the date + totals) and payout_entries (one row per employee
-- in that batch). The screen's own cash/bank total is debited from the
-- submitting user's own PC wallet via the existing wallet_self_debit RPC
-- (called from the client, same two-call pattern ExpenseForm.jsx already
-- uses for cash expenses) — not done here, since wallet_self_debit isn't
-- itself transactional with this insert in that precedent either.
--
-- employees.id is uuid (confirmed via information_schema — not bigint).
-- Only `full_name` is NOT NULL without a default on that table, so the
-- screen's inline "+ Add '<name>' as new employee" can insert with just
-- that (status defaults to 'probation', the real column default).
-- employees' own RLS only allows is_admin_user()/is_finance_hr() to
-- INSERT directly — whoever runs payroll entry may be neither, so the
-- quick-add goes through fn_quick_add_employee (SECURITY DEFINER) rather
-- than a direct client insert.
--
-- Both RPCs gate on the SAME two permissions the screen itself checks
-- (finance.salary_payouts AND hr.employees.salary_view, admin.dashboard
-- bypasses) via a shared helper, rather than the table's own
-- is_admin_user()/is_finance_hr() — those may be a different population,
-- and letting the DB-side gate drift from the UI gate is how an RPC ends
-- up reachable (or blocked) differently than the screen that calls it.

BEGIN;

CREATE TABLE IF NOT EXISTS public.salary_payout_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payout_date date NOT NULL,
  total_cash_paise bigint NOT NULL DEFAULT 0,
  total_bank_paise bigint NOT NULL DEFAULT 0,
  created_by uuid NOT NULL REFERENCES public.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.salary_payout_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES public.salary_payout_batches(id) ON DELETE CASCADE,
  employee_id uuid NOT NULL REFERENCES public.employees(id),
  payout_date date NOT NULL,
  cash_paise bigint NOT NULL DEFAULT 0,
  bank_paise bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_salary_payout_entries_batch ON public.salary_payout_entries(batch_id);
CREATE INDEX IF NOT EXISTS idx_salary_payout_entries_employee ON public.salary_payout_entries(employee_id);
CREATE INDEX IF NOT EXISTS idx_salary_payout_entries_date ON public.salary_payout_entries(payout_date);

ALTER TABLE public.salary_payout_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.salary_payout_entries ENABLE ROW LEVEL SECURITY;

-- Shared auth check — mirrors SalaryPayouts.jsx's own `canView` exactly.
-- Plain (not SECURITY DEFINER): called only from inside the SECURITY
-- DEFINER functions below, so it already runs with their elevated rights;
-- auth.uid() still resolves to the real caller regardless.
CREATE OR REPLACE FUNCTION public._salary_payout_caller_ok()
RETURNS boolean
LANGUAGE sql STABLE SET search_path TO 'public' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid()
      AND (
        'admin.dashboard' = ANY(COALESCE(p.desktop_permissions, '{}'))
        OR 'admin.dashboard' = ANY(COALESCE(p.mobile_permissions, '{}'))
        OR (
          ('finance.salary_payouts' = ANY(COALESCE(p.desktop_permissions, '{}')) OR 'finance.salary_payouts' = ANY(COALESCE(p.mobile_permissions, '{}')))
          AND
          ('hr.employees.salary_view' = ANY(COALESCE(p.desktop_permissions, '{}')) OR 'hr.employees.salary_view' = ANY(COALESCE(p.mobile_permissions, '{}')))
        )
      )
  );
$$;

CREATE POLICY sel_salary_payout_batches ON public.salary_payout_batches
  FOR SELECT TO authenticated USING (public._salary_payout_caller_ok());

CREATE POLICY sel_salary_payout_entries ON public.salary_payout_entries
  FOR SELECT TO authenticated USING (public._salary_payout_caller_ok());

-- Quick-add: used by the screen's "+ Add '<name>' as new employee" inline
-- option. Status is left to its column default ('probation') rather than
-- set explicitly — this is a real, immediately-paid staff member, not a
-- pending self-service signup (that's a different status, used by
-- PublicEmployeeForm.jsx). HR can fill in the rest of the profile later.
CREATE OR REPLACE FUNCTION public.fn_quick_add_employee(p_full_name text)
RETURNS public.employees
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_name text := trim(coalesce(p_full_name, ''));
  v_row public.employees%rowtype;
BEGIN
  IF NOT public._salary_payout_caller_ok() THEN
    RAISE EXCEPTION 'Not authorized';
  END IF;
  IF v_name = '' THEN
    RAISE EXCEPTION 'Name is required';
  END IF;

  INSERT INTO public.employees (full_name, created_by)
  VALUES (v_name, auth.uid())
  RETURNING * INTO v_row;

  RETURN v_row;
END;
$$;

-- p_entries: jsonb array of {"employee_id": "<uuid>", "cash_paise": n, "bank_paise": n}.
-- Rows with both amounts 0 are silently skipped (the UI already filters
-- these out before calling, this is just a server-side backstop).
CREATE OR REPLACE FUNCTION public.fn_record_salary_payout(p_date date, p_entries jsonb)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_batch_id bigint;
  v_entry jsonb;
  v_emp_id uuid;
  v_cash bigint;
  v_bank bigint;
  v_total_cash bigint := 0;
  v_total_bank bigint := 0;
BEGIN
  IF NOT public._salary_payout_caller_ok() THEN
    RAISE EXCEPTION 'Not authorized';
  END IF;
  IF p_date IS NULL THEN
    RAISE EXCEPTION 'Payment date is required';
  END IF;
  IF p_date > current_date THEN
    RAISE EXCEPTION 'Payment date cannot be in the future';
  END IF;
  IF jsonb_typeof(p_entries) <> 'array' OR jsonb_array_length(p_entries) = 0 THEN
    RAISE EXCEPTION 'Add at least one employee';
  END IF;

  INSERT INTO public.salary_payout_batches (payout_date, created_by)
  VALUES (p_date, auth.uid())
  RETURNING id INTO v_batch_id;

  FOR v_entry IN SELECT * FROM jsonb_array_elements(p_entries) LOOP
    v_emp_id := nullif(v_entry->>'employee_id', '')::uuid;
    v_cash   := coalesce((v_entry->>'cash_paise')::bigint, 0);
    v_bank   := coalesce((v_entry->>'bank_paise')::bigint, 0);

    IF v_emp_id IS NULL THEN
      RAISE EXCEPTION 'Every row needs an employee';
    END IF;
    IF v_cash < 0 OR v_bank < 0 THEN
      RAISE EXCEPTION 'Amounts cannot be negative';
    END IF;
    IF v_cash = 0 AND v_bank = 0 THEN
      CONTINUE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.employees WHERE id = v_emp_id) THEN
      RAISE EXCEPTION 'Unknown employee';
    END IF;

    INSERT INTO public.salary_payout_entries (batch_id, employee_id, payout_date, cash_paise, bank_paise)
    VALUES (v_batch_id, v_emp_id, p_date, v_cash, v_bank);

    v_total_cash := v_total_cash + v_cash;
    v_total_bank := v_total_bank + v_bank;
  END LOOP;

  IF v_total_cash = 0 AND v_total_bank = 0 THEN
    RAISE EXCEPTION 'Enter at least one cash or bank amount';
  END IF;

  UPDATE public.salary_payout_batches
  SET total_cash_paise = v_total_cash, total_bank_paise = v_total_bank
  WHERE id = v_batch_id;

  RETURN v_batch_id;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_quick_add_employee(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_record_salary_payout(date, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_quick_add_employee(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_record_salary_payout(date, jsonb) TO authenticated;

NOTIFY pgrst, 'reload schema';

COMMIT;
